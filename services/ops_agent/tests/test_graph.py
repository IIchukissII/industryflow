TENANT = "0b2f503a-1c2d-4e5f-8a9b-0c1d2e3f4a5b"
ALERT = {
    "status": "firing", "fingerprint": "f1", "startsAt": "2026-10-31T10:00:00Z",
    "labels": {"alertname": "IndustryFlowRedisMemoryHigh", "severity": "warning", "instance": "redis-exporter:9121"},
    "annotations": {"summary": "Redis is near its memory limit", "services": "redis, api-gateway"},
    "generatorURL": "http://prometheus:9090/graph?g0.expr=redis_memory_used_bytes&g0.tab=1",
}


OLD, NEW = "a" * 40, "0123456789abcdef0123456789abcdef01234567"
REVISIONS = [  # api-gateway deployed at 09:55, three minutes before the alert's window ends near 10:00
    {"metric": {"component": "api-gateway", "revision": OLD}, "values": [[1793440800, "1"], [1793443800, "1"]]},
    {"metric": {"component": "api-gateway", "revision": NEW}, "values": [[1793443920, "1"], [1793444400, "1"]]},
    {"metric": {"component": "ml-service-api", "revision": NEW}, "values": [[1793440800, "1"], [1793444400, "1"]]},
]


class FakeTools:
    def __init__(self, fail=()):
        self.calls, self.fail = [], fail

    async def call(self, name, arguments):
        self.calls.append((name, arguments))
        if name in self.fail:
            raise ConnectionError("store unreachable")
        if name == "prometheus_range" and graph.REVISIONS_METRIC in arguments["query"]:
            return {"series": REVISIONS}
        if name == "prometheus_range":
            return {"series": [{"metric": {"job": "redis"}, "values": [[1, "10"], [2, "95"]]}]}
        if name == "loki_errors":
            return {"lines": [{"ts": "1", "line": f"OOM command not allowed for tenant {TENANT} by ops@example.com"}]}
        if name == "active_alerts":
            return {"alerts": [{"alertname": "IndustryFlowRedisMemoryHigh"}, {"alertname": "IndustryFlowKafkaConsumerLag"}]}
        return {"rows": [{"symptom": "Redis refuses writes", "cause": "memory limit", "fix": "raise maxmemory", "source": "capacity.md"}]}


class FakeWriter:
    def __init__(self, fail=False):
        self.prompts, self.fail = [], fail

    async def write(self, system, prompt):
        self.prompts.append(prompt)
        if self.fail:
            raise ModelDeclined("declined")
        return Written("What happened: memory high [E1].", "claude-opus-5-5")


class FakePublisher:
    def __init__(self):
        self.notes = []

    async def publish(self, note):
        self.notes.append(note)


async def _run(config, tools=None, writer=None):
    tools, writer, publisher = tools or FakeTools(), writer or FakeWriter(), FakePublisher()
    await graph.build(config(), tools, writer, publisher).ainvoke({"alert": ALERT})
    return tools, writer, publisher.notes[0]


@pytest.mark.asyncio
async def test_evidence_is_gathered_for_the_rule_and_its_services(config):
    tools, _, _ = await _run(config)
    calls = [(n, a.get("query") or a.get("service")) for n, a in tools.calls]
    assert calls[:4] == [("prometheus_range", "redis_memory_used_bytes"), ("loki_errors", "redis"),
                         ("loki_errors", "api-gateway"), ("loki_errors", "redis-exporter")]



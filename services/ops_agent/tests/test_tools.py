"""The tools are served over MCP and read only the monitoring plane (ADR-0045 dec 2, ADR-0046 dec 2)."""

import json

import httpx
import pytest
from mcp import Client

import tools


def _transport(seen):
    def handle(request: httpx.Request) -> httpx.Response:
        seen.append(request)
        assert request.method == "GET", "a tool only reads"
        if request.url.path == "/api/v1/query_range":
            return httpx.Response(200, json={"data": {"result": [
                {"metric": {"job": "redis"}, "values": [[i, str(i)] for i in range(300)]}] * 12}})
        if request.url.path == "/loki/api/v1/query_range":
            return httpx.Response(200, json={"data": {"result": [
                {"stream": {"service": "redis"}, "values": [["2", "ERROR b"], ["1", "ERROR a" + "x" * 900]]}]}})
        if request.url.path == "/api/v2/alerts":
            return httpx.Response(200, json=[{"labels": {"alertname": "IndustryFlowRedisDown"},
                                              "startsAt": "t", "status": {"state": "active"}}])
        return httpx.Response(404)
    return httpx.MockTransport(handle)


async def _call(server, name, args):
    async with Client(server) as client:
        result = await client.call_tool(name, args)
    return json.loads("".join(p.text for p in result.content))


@pytest.mark.asyncio
async def test_the_tool_set_is_the_monitoring_plane(config):
    async with Client(tools.build_server(config(), _transport([]))) as client:
        names = sorted(t.name for t in (await client.list_tools()).tools)
    assert names == ["active_alerts", "loki_errors", "prometheus_range", "runbook_rows"]


@pytest.mark.asyncio
async def test_metrics_are_capped(config):
    out = await _call(tools.build_server(config(), _transport([])), "prometheus_range",
                      {"query": "redis_up", "start": "a", "end": "b"})
    assert len(out["series"]) == tools.MAX_SERIES and out["truncated"]
    assert len(out["series"][0]["values"]) == tools.MAX_POINTS


@pytest.mark.asyncio
async def test_logs_select_the_service_and_only_error_lines(config):
    seen = []
    out = await _call(tools.build_server(config(), _transport(seen)), "loki_errors",
                      {"service": 'redis"} or {x="', "start": "a", "end": "b"})
    query = seen[0].url.params["query"]
    assert query.startswith('{service="redis} or {x="}') and "error" in query
    assert [l["ts"] for l in out["lines"]] == ["2", "1"]
    # Cut at a space, never through a value the redactor would then see only half of.
    assert out["lines"][1]["line"] == "ERROR …"


@pytest.mark.asyncio
async def test_runbook_rows_come_from_the_real_runbooks(config):
    out = await _call(tools.build_server(config(), _transport([])), "runbook_rows",
                      {"text": "Readings were dead-lettered"})
    assert out["rows"], "the dead-letter runbook has a matching row"


@pytest.mark.asyncio
async def test_the_agent_reaches_its_tools_over_stdio(config, monkeypatch):
    """The deployed path: the tool server as a subprocess, spoken to over MCP's stdio transport, and
    given no secret (only the endpoint settings pass)."""
    import app
    from conftest import REPO

    monkeypatch.setenv("OPS_AGENT_RUNBOOKS_DIR", str(REPO / "docs" / "operations"))
    monkeypatch.setenv("OPS_AGENT_WEBHOOK_SECRET", "s" * 40)
    mcp_tools = app.McpTools.from_config(config())
    assert "OPS_AGENT_WEBHOOK_SECRET" not in mcp_tools._target.env
    async with mcp_tools:
        out = await mcp_tools.call("runbook_rows", {"text": "Readings were dead-lettered"})
    assert out["rows"]


@pytest.mark.asyncio
async def test_a_note_is_pushed_to_its_own_log_stream(config):
    import publish

    seen = []

    def handle(request):
        seen.append(request)
        return httpx.Response(204)

    note = {"alertname": "IndustryFlowRedisDown", "severity": "warning", "text": "Generated by …"}
    await publish.LokiPublisher(config(), httpx.MockTransport(handle)).publish(note)
    body = json.loads(seen[0].content)
    stream = body["streams"][0]
    assert seen[0].url.path == "/loki/api/v1/push"
    assert stream["stream"] == {"job": "ops-agent", "alertname": "IndustryFlowRedisDown", "severity": "warning"}
    assert json.loads(stream["values"][0][1]) == note



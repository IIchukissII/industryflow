"""Resolve the immutable digests of the first-party images the chart deploys and emit a Helm values
overlay that pins each by digest (ADR-0009). Run through scripts/pin-image-digests.sh.

The image list is READ FROM values.yaml, never kept here: every mapping that carries both `image`
and `digest` is a first-party image, and the overlay sets that mapping's `digest`. A hand list next
to the chart drifted the way such lists do — it kept a retired image and missed seven live ones —
and an image missing from the overlay silently ships on the mutable tag.

Usage:  pin_image_digests.py [TAG]        (TAG defaults to "latest"); writes the overlay to stdout.
Env:    REGISTRY      registry/namespace prefix (default: the chart's image.registry)
        GITHUB_TOKEN  PAT for private GHCR packages (else `gh auth token`; public ones need none)
Needs:  python3 with PyYAML.
"""

from __future__ import annotations

import base64
import json
import os
import shutil
import subprocess
import sys
import urllib.request
from pathlib import Path

import yaml

VALUES = Path(__file__).resolve().parent.parent / "deploy" / "helm" / "industryflow" / "values.yaml"

_ACCEPT = ", ".join([
    "application/vnd.oci.image.index.v1+json",
    "application/vnd.docker.distribution.manifest.list.v2+json",
    "application/vnd.docker.distribution.manifest.v2+json",
])


def first_party_images(values: dict) -> dict[tuple[str, ...], str]:
    """Every first-party image the chart deploys, keyed by its values path: a mapping with both
    `image` and `digest` (third-party images are pinned inline as `repo:tag@sha256:…` instead)."""
    found: dict[tuple[str, ...], str] = {}

    def walk(node, path):
        if not isinstance(node, dict):
            return
        if "image" in node and "digest" in node and isinstance(node["image"], str):
            found[path] = node["image"]
        for key, child in node.items():
            walk(child, path + (key,))

    walk(values, ())
    return found


def render_overlay(digests: dict[tuple[str, ...], str], tag: str, registry: str) -> str:
    """The overlay, nested exactly as values.yaml so `-f` merges onto the same keys."""
    tree: dict = {}
    for path, digest in digests.items():
        node = tree
        for key in path:
            node = node.setdefault(key, {})
        node["digest"] = digest
    # The SPDX tags belong to the GENERATED file; the markers stop `reuse` reading them as this file's.
    # REUSE-IgnoreStart
    header = (
        "# SPDX-FileCopyrightText: 2026 The IndustryFlow contributors\n"
        "# SPDX-License-Identifier: AGPL-3.0-or-later\n"
    )
    # REUSE-IgnoreEnd
    header += (
        "#\n"
        "# GENERATED by scripts/pin-image-digests.sh from values.yaml — do not edit by hand.\n"
        f"# First-party image digests for tag '{tag}' from {registry}. Apply with: -f values-digests.yaml\n"
    )
    return header + yaml.safe_dump(tree, sort_keys=False, default_flow_style=False)


def _token(repo: str) -> str:
    pat = os.environ.get("GITHUB_TOKEN", "")
    if not pat and shutil.which("gh"):
        pat = subprocess.run(["gh", "auth", "token"], capture_output=True, text=True).stdout.strip()
    req = urllib.request.Request(f"https://ghcr.io/token?service=ghcr.io&scope=repository:{repo}:pull")
    if pat:
        req.add_header("Authorization", "Bearer " + base64.b64encode(pat.encode()).decode())
    with urllib.request.urlopen(req, timeout=30) as resp:
        return json.load(resp)["token"]


def resolve(registry: str, image: str, tag: str) -> str:
    """The manifest-list (multi-arch) digest of registry/image:tag, via the registry v2 API."""
    host, _, namespace = registry.partition("/")
    if host != "ghcr.io":
        raise SystemExit(f"error: only ghcr.io is supported for first-party digests (got {host!r})")
    repo = f"{namespace}/{image}"
    req = urllib.request.Request(f"https://ghcr.io/v2/{repo}/manifests/{tag}", method="HEAD")
    req.add_header("Accept", _ACCEPT)
    req.add_header("Authorization", f"Bearer {_token(repo)}")
    with urllib.request.urlopen(req, timeout=30) as resp:
        digest = resp.headers.get("Docker-Content-Digest", "")
    if not digest.startswith("sha256:"):
        raise SystemExit(f"error: no digest for {image}:{tag}")
    return digest


def main(argv: list[str]) -> int:
    tag = argv[1] if len(argv) > 1 else "latest"
    values = yaml.safe_load(VALUES.read_text())
    registry = os.environ.get("REGISTRY") or values["image"]["registry"]
    images = first_party_images(values)
    digests = {path: resolve(registry, image, tag) for path, image in images.items()}
    sys.stdout.write(render_overlay(digests, tag, registry))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))

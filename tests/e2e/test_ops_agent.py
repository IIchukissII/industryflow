"""The infrastructure agent explains a platform alert (ADR-0046): an alert entered into the operator's
alert router reaches the agent through its receiver, and a note marked as generated lands in the log
store with its evidence. The receiver refuses a caller without the shared secret.

The alert is entered directly, not raised by a rule: a rule needs its five minutes of failure, and the
path under test starts at the router. Where the agent is not enabled (it is off by default, ADR-0045
dec 8), the journey checks that it is really off: no container and no receiver pointing at it."""
import json
import time
import urllib.parse
import uuid
from datetime import datetime, timedelta, timezone

ALERTNAME = "IndustryFlowE2EOpsProbe"
NOTE_TIMEOUT = 240  # the router's group wait (30 s) plus the agent's evidence and model call


def _router(env, *argv: str) -> str:
    """A command inside the alert router's container: it has amtool and wget, and reaches the log store
    and the agent on the platform network (the log store's own image has no shell)."""
    return env.run("docker", "exec", "industryflow-alertmanager", *argv)


def _agent_running(env) -> bool:
    out = env.run("docker", "ps", "--filter", "name=^industryflow-ops-agent$", "--filter", "status=running",
                  "--format", "{{.Names}}")
    return out.strip() == "industryflow-ops-agent"


def _notes(env, run: str) -> list[dict]:
    query = urllib.parse.urlencode({
        "query": f'{{job="ops-agent", alertname="{ALERTNAME}"}} |= `{run}`',
        "start": str(int((time.time() - 3600) * 1e9)), "limit": "5"})
    body = json.loads(_router(env, "wget", "-qO-", f"http://loki:3100/loki/api/v1/query_range?{query}"))
    return [json.loads(line) for stream in body["data"]["result"] for _, line in stream["values"]]


def _alert(env, run: str, ends: datetime) -> None:
    _router(env, "amtool", "--alertmanager.url=http://localhost:9093", "alert", "add",
            f"alertname={ALERTNAME}", "severity=warning", f"run={run}",
            "--annotation=summary=End-to-end probe of the infrastructure agent",
            "--annotation=description=Entered by tests/e2e/test_ops_agent.py; no service is failing.",
            "--annotation=services=ops-agent",
            f"--end={ends.strftime('%Y-%m-%dT%H:%M:%SZ')}")


def test_a_platform_alert_becomes_a_generated_note_in_the_log_store(env):
    if not _agent_running(env):
        # Off by default: then it is off, not half on.
        # Compared as a flag: the config holds the receiver's secret, and a failed assertion prints its
        # operands.
        receiver_points_at_agent = "ops-agent:8095" in _router(env, "cat", "/etc/alertmanager/alertmanager.yml")
        assert not receiver_points_at_agent, "the alert router sends to an agent that is not running"
        return

    run = uuid.uuid4().hex[:12]
    _alert(env, run, datetime.now(timezone.utc) + timedelta(minutes=10))
    try:
        deadline, notes = time.time() + NOTE_TIMEOUT, []
        while time.time() < deadline and not notes:
            time.sleep(5)
            notes = _notes(env, run)
        assert notes, f"no note for the probe alert within {NOTE_TIMEOUT}s"
        note = notes[0]
        assert note["generated"] is True and note["model"]
        assert note["text"].startswith(("Generated by the infrastructure agent with",
                                        "Built by the infrastructure agent from the evidence alone"))
        assert f"run={run}" in note["alert"] and "@" in note["key"]
        for source in ("alert router", "logs of ops-agent", "alert runbook"):
            assert source in note["evidence"], (source, note["evidence"])
        assert isinstance(note["redactions"], dict)

        # One firing, one note: the router repeats it, the agent does not explain it again.
        time.sleep(40)
        assert len(_notes(env, run)) == 1
    finally:
        _alert(env, run, datetime.now(timezone.utc) - timedelta(seconds=1))


def test_the_receiver_refuses_a_caller_without_the_secret(env):
    if not _agent_running(env):
        return
    out = _router(env, "sh", "-c",
                  "wget -S -O- --header='Content-Type: application/json' --post-data='{\"alerts\": []}' "
                  "http://ops-agent:8095/alertmanager 2>&1 || true")
    assert " 401 " in out, out[-400:]

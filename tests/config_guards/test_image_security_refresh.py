"""
Every image that takes security fixes at build time re-runs that build daily, and only those do.

Two kinds of layer pick their security fixes up at build: `apt-get upgrade` (the Spark images patch
their pinned Ubuntu) and a pip resolve whose transitive dependencies are unpinned (every Python image
except the MLflow server, whose requirements are a full pip-compile lock). The persistent build cache
replays either layer verbatim, so its patch level freezes at the last cache write and the Trivy gate
goes red on a CVE a fresh build would not have — #257/#259 for the OS, GHSA-6q48-6c7w-9gw2 (certifi)
for Python. The daily epoch reaches a layer only when the matrix entry sets `security_refresh` AND
the Dockerfile declares `ARG SECURITY_REFRESH` and uses it before that layer. Either side alone fails
silently, so this reads both.
"""
import re

import pytest
from _repo import ROOT, load_yaml

ARG = re.compile(r"^ARG SECURITY_REFRESH\b", re.MULTILINE)
USE = re.compile(r"^RUN echo \"security refresh: \$\{SECURITY_REFRESH\}\"", re.MULTILINE)
REFRESHING = re.compile(r"^RUN\b.*\b(pip install|apt-get upgrade)\b", re.MULTILINE)
PIP_REQUIREMENTS = re.compile(r"pip install[^\n]*-r\s+(\S+)")
LOCK_HEADER = "autogenerated by pip-compile"

MATRIX = load_yaml(".github/workflows/images.yml")["jobs"]["build-scan"]["strategy"]["matrix"]["include"]


def _continued(text: str) -> str:
    return text.replace("\\\n", " ")


def _fully_locked(entry: dict, text: str) -> bool:
    """Every pip install in the image reads a pip-compile lock, so a resolve has nothing to move."""
    installs = re.findall(r"^RUN\b[^\n]*pip install[^\n]*", text, re.MULTILINE)
    if not installs:
        return False
    # The name each copied file has in the image (a destination ending in `/` keeps the source's).
    sources = {
        (dest.rstrip("/").split("/")[-1] if not dest.endswith("/") else src.split("/")[-1]): src
        for src, dest in re.findall(r"^COPY\s+(?!--from)(\S+)\s+(\S+)\s*$", text, re.MULTILINE)
    }
    for line in installs:
        m = PIP_REQUIREMENTS.search(line)
        if not m:
            return False
        src = sources.get(m.group(1).split("/")[-1], m.group(1))
        if LOCK_HEADER not in (ROOT / entry["context"] / src).read_text():
            return False
    return True


def test_the_matrix_is_found_and_the_guard_bites():
    assert len(MATRIX) >= 15
    assert sum(bool(e.get("security_refresh")) for e in MATRIX) >= 10, "the guard would be vacuous"


@pytest.mark.parametrize("entry", MATRIX, ids=[e["name"] for e in MATRIX])
def test_an_image_refreshes_exactly_when_a_layer_takes_fixes_at_build(entry):
    text = _continued((ROOT / entry["file"]).read_text())
    needs = bool(REFRESHING.search(text)) and not _fully_locked(entry, text)
    flagged = bool(entry.get("security_refresh"))
    assert needs == flagged, (
        f"{entry['name']}: a layer {'takes' if needs else 'takes no'} security fixes at build, but the "
        f"matrix {'does not set' if needs else 'sets'} security_refresh"
    )
    declared = bool(ARG.search(text))
    assert declared == flagged, (
        f"{entry['file']}: the matrix {'passes' if flagged else 'does not pass'} SECURITY_REFRESH, but "
        f"the Dockerfile {'does not declare' if flagged else 'declares'} it"
    )
    if not flagged:
        return
    first_fix = REFRESHING.search(text).start()
    use = USE.search(text)
    assert use and use.start() <= first_fix, (
        f"{entry['file']}: SECURITY_REFRESH must be used at or before the first layer that takes fixes, "
        "or that layer keeps its cache key"
    )


def test_the_epoch_reaches_the_build_only_for_flagged_images():
    steps = load_yaml(".github/workflows/images.yml")["jobs"]["build-scan"]["steps"]
    epoch = next(s for s in steps if s.get("id") == "epoch")
    build = next(s for s in steps if s.get("uses", "").startswith("docker/build-push-action"))
    assert epoch["if"] == "matrix.security_refresh"
    assert "matrix.security_refresh" in build["with"]["build-args"]
    assert "SECURITY_REFRESH=" in build["with"]["build-args"]
